if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = JSON.parse(readFileSync(resolve(tokenRoot, 'design/tokens.json'), 'utf8'));
  for (const [path, content] of Object.entries(generateTokens(source))) {
    const target = resolve(tokenRoot, path);
    if (process.argv.includes('--check')) {
      if (readFileSync(target, 'utf8') !== content) throw new Error(`Stale generated tokens: ${path}`);
    } else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
  }
}
